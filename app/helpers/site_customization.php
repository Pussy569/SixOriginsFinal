    $result->free();
    if ($saved) {
        $settings = array_merge($settings, $saved);
    }

    $contentTexts = is_string($settings['content_texts']) ? json_decode($settings['content_texts'], true) : $settings['content_texts'];
    $contentDefaults = site_customization_content_defaults();
